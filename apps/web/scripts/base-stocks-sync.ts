/**
 * Regenerates src/lib/base-stocks/coinbase-list.ts from Base's own list of
 * Coinbase Tokenized Stocks (https://www.base.org/api/stocks) and refuses to
 * write unless EVERY token passes on chain on Base 8453: B20 factory
 * isB20() == true, decimals() == 8, symbol() == the listed ticker.
 *
 *   npx tsx scripts/base-stocks-sync.ts          # check, print the diff, write
 *   npx tsx scripts/base-stocks-sync.ts --dry    # check and print only
 *
 * Addresses come from the issuer's table, never matched by ticker (#280).
 */
import { createPublicClient, erc20Abi, getAddress, http, parseAbi } from "viem";
import { base } from "viem/chains";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { COINBASE_BASE_STOCKS } from "../src/lib/base-stocks/coinbase-list";

const FACTORY = "0xB20f000000000000000000000000000000000000" as const;
const FACTORY_ABI = parseAbi(["function isB20(address) view returns (bool)"]);

async function main() {
  const dry = process.argv.includes("--dry");
  const r = await fetch("https://www.base.org/api/stocks", { headers: { "user-agent": "Mozilla/5.0", accept: "application/json" } });
  if (!r.ok) throw new Error(`base.org/api/stocks answered ${r.status}`);
  const list = ((await r.json()) as { stocks: { ticker: string; address: string; name: string }[] }).stocks;
  const c = createPublicClient({ chain: base, transport: http(process.env.BASE_RPC_URL || "https://base-rpc.publicnode.com"), batch: { multicall: true } });
  const checked = await Promise.all(list.map(async (s) => {
    const token = getAddress(s.address);
    const [symbol, decimals, isB20] = await Promise.all([
      c.readContract({ address: token, abi: erc20Abi, functionName: "symbol" }).catch(() => null),
      c.readContract({ address: token, abi: erc20Abi, functionName: "decimals" }).catch(() => null),
      c.readContract({ address: FACTORY, abi: FACTORY_ABI, functionName: "isB20", args: [token] }).catch(() => null),
    ]);
    return { ...s, token, ok: symbol === s.ticker && decimals === 8 && isB20 === true, symbol, decimals, isB20 };
  }));
  // Logo: the token's OWN metadata. contractURI() on chain → Coinbase's JSON →
  // `image`, kept only if it answers an image. A token without one stays null
  // (the UI falls back), never a guessed URL. 16 at a time: it is Coinbase's API.
  const CONTRACT_URI = parseAbi(["function contractURI() view returns (string)"]);
  const images: (string | null)[] = [];
  for (let i = 0; i < checked.length; i += 16) {
    images.push(...await Promise.all(checked.slice(i, i + 16).map(async (x) => {
      try {
        const uri = await c.readContract({ address: x.token, abi: CONTRACT_URI, functionName: "contractURI" });
        if (!/^https:\/\//.test(uri)) return null;
        const meta = (await (await fetch(uri)).json()) as { image?: unknown };
        const img = typeof meta.image === "string" && /^https:\/\//.test(meta.image) ? meta.image : null;
        if (!img) return null;
        // The CDN serves these as binary/octet-stream, so check the bytes (PNG
        // or JPEG magic), not the content-type header.
        const r = await fetch(img, { redirect: "follow", headers: { range: "bytes=0-7" } });
        if (!r.ok) return null;
        const b = new Uint8Array(await r.arrayBuffer());
        const png = b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47;
        const jpg = b[0] === 0xff && b[1] === 0xd8;
        return png || jpg ? img : null;
      } catch { return null; }
    })));
  }
  const withImage = images.filter(Boolean).length;
  console.log(`logos: ${withImage} of ${checked.length} from each token's contractURI`);
  const bad = checked.filter((x) => !x.ok);
  const before = new Set(COINBASE_BASE_STOCKS.map((s) => s.token.toLowerCase()));
  const added = checked.filter((x) => !before.has(x.token.toLowerCase())).map((x) => x.ticker);
  const removed = COINBASE_BASE_STOCKS.filter((s) => !checked.some((x) => x.token.toLowerCase() === s.token.toLowerCase())).map((s) => s.symbol);
  console.log(`listed ${checked.length} · on-chain pass ${checked.length - bad.length} · added ${added.join(", ") || "none"} · removed ${removed.join(", ") || "none"}`);
  for (const b of bad) console.log(`FAIL ${b.ticker} ${b.token} symbol=${b.symbol} decimals=${b.decimals} isB20=${b.isB20}`);
  if (bad.length) { console.error("Refusing to write: every listed token must pass on chain."); process.exit(1); }
  if (dry) return;

  const esc = (t: string) => t.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const rows = checked.map((x, i) => `  { ticker: "${esc(x.ticker.replace(/c$/, ""))}", symbol: "${esc(x.ticker)}", name: "${esc(x.name)}", token: "${x.token}", image: ${images[i] ? `"${esc(images[i]!)}"` : "null"} },`);
  const today = new Date().toISOString().slice(0, 10);
  const file = `/**
 * Every Coinbase Tokenized Stock on Base 8453, as Base publishes them.
 *
 * GENERATED by scripts/base-stocks-sync.ts from https://www.base.org/api/stocks
 * (the API behind base.org/stocks) on ${today}, then asserted on chain token by
 * token: B20 factory isB20() == true, decimals() == 8, symbol() == the listed
 * ticker. ${checked.length} of ${checked.length} passed. \`image\` is the token's own logo, read
 * from contractURI() → Coinbase's metadata JSON and kept only if it answers an
 * image (${withImage} of ${checked.length}); null means none was served. Re-run the script to refresh; do not hand-edit.
 *
 * This is the MARKETS catalogue (what /markets lists on Base). It is NOT
 * lib/base-stocks/registry.ts: BASE_STOCKS is Blue Hood's allowlist for grading
 * oracle-vs-DEX drift, with its own pool bar, and stays as small as that bar
 * keeps it. Listing a token here claims only "Coinbase issued this contract".
 */
import type { Address } from "viem";

export interface CoinbaseBaseStock { ticker: string; symbol: string; name: string; token: Address; image: string | null }

export const COINBASE_BASE_STOCKS_SOURCE = "https://www.base.org/api/stocks" as const;
export const COINBASE_BASE_STOCKS_CHECKED_AT = "${today}" as const;

export const COINBASE_BASE_STOCKS: readonly CoinbaseBaseStock[] = [
${rows.join("\n")}
];
`;
  writeFileSync(join(__dirname, "../src/lib/base-stocks/coinbase-list.ts"), file);
  console.log("wrote src/lib/base-stocks/coinbase-list.ts");
}

main().catch((e) => { console.error(e); process.exit(1); });
